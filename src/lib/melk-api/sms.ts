/**
 * دسته‌بندی خطاهای پیامک سامانه‌های ملک تبریز — خالص و تست‌پذیر
 * ------------------------------------------------------
 * P6.5-09 (دستور مالک — رفع باگ سهمیهٔ مشترک پیامک PM/ARM):
 *
 * واقعیت کاوش‌شده: هر دو سامانه PM و ARM مسیر احراز هویت یکسان
 * (authentication/otp/{code}) دارند و دروازهٔ پیامک ملک تبریز برای
 * «یک شماره موبایل» سهمیه و خنک‌سازی مشترک اعمال می‌کند. نتیجه:
 * اتصال به PM و بلافاصله درخواست پیامک ARM (یا بالعکس) با خطای
 * سمت سرور رد می‌شود — «پیامک قبلاً ارسال شده» یا «به سقف پیامک
 * رسیدید».
 *
 * رفتار درست ما (صفر تغییر سمت سرور مبدأ — صفر تماس اضافی):
 *   · ALREADY_SENT  → پیامک «همین حالا» برای این شماره ارسال شده و
 *     هنوز معتبر است ⇒ نرم‌موفق: کاربر همان کد دریافت‌شده را وارد
 *     کند (بدون ثبت تلاش ناموفق و بدون اشغال سهمیه).
 *   · LIMIT_REACHED → سقف ارسال «سمت خود سامانه ملک تبریز» پر شده ⇒
 *     پیام شفاف با راهنمایی انتظار؛ خطا به‌عنوان تلاش شمرده نمی‌شود
 *     (قفل خود-تمدیدشونده نمی‌سازیم — عین HOTFIX-04).
 *   · سایر خطاها    → عین رفتار قبلی (خطای واقعی ارسال).
 */

/** نتیجهٔ دسته‌بندی یک پیام خطای ارسال پیامک */
export type SmsSendFailureKind = "ALREADY_SENT" | "LIMIT_REACHED" | "OTHER";

export interface SmsSendFailure {
  kind: SmsSendFailureKind;
  /** پیام فارسی کاربرپسند برای همین دسته */
  userMessage: string;
}

/**
 * الگوهای پیام «قبلاً ارسال شده» — دروازهٔ پیامک ملک تبریز این مفهوم را
 * با ترکیب «قبلا + ارسال/فرستاده/کد» بیان می‌کند (فارسی/لاتین‌نویس).
 */
const ALREADY_SENT_PATTERNS: RegExp[] = [
  /قبلا[\s\u200c]*ارسال/,
  /ارسال[\s\u200c]*شده[\s\u200c]*(است|می[\s\u200c]*باشد)/,
  /already[\s_-]*sent/i,
  /sms[\s_-]*already/i,
  /کد[\s\u200c]*(پیامک|تأیید|تایید)?[\s\u200c]*قبلا/,
];

/**
 * الگوهای پیام «سقف پیامک» — سهمیه/محدودیت ارسال سمت سرور مبدأ
 * (نه محدودساز نرخ محلی ما — آن پیام خودش را داریم).
 */
const LIMIT_PATTERNS: RegExp[] = [
  /سقف/,
  /(به|تا|در)[\s\u200c]*(حد[\s\u200c]*مجاز|محدودیت)/,
  /حد[\s\u200c]*مجاز/,
  /تعداد[\s\u200c]*(درخواست[\s\u200c]*)?(کد[\s\u200c]*)?پیامک[\s\u200c]*(بیش|زیاد)/,
  /too[\s_-]*many/i,
  /limit/i,
];

/** دسته‌بندی پیام خطای ارسال پیامک — خالص (صفر وابستگی) */
export function classifySmsSendFailure(rawMessage: string): SmsSendFailure {
  const msg = String(rawMessage ?? "");

  if (ALREADY_SENT_PATTERNS.some((re) => re.test(msg))) {
    return {
      kind: "ALREADY_SENT",
      userMessage:
        "پیامک تأیید همین حالا برای این شماره ارسال شده و هنوز معتبر است — همان کد پیامکی دریافت‌شده (از سامانه PM یا ARM) را وارد کنید. اگر آن کد پذیرفته نشد، ۲ تا ۳ دقیقه صبر کنید و دوباره درخواست بدهید.",
    };
  }

  if (LIMIT_PATTERNS.some((re) => re.test(msg))) {
    return {
      kind: "LIMIT_REACHED",
      userMessage:
        "سامانه ملک تبریز موقتاً ارسال پیامک جدید برای این شماره را محدود کرده است (سقف ارسال سمت خود آن سامانه). چند دقیقه دیگر دوباره درخواست دهید — کد قبلی تا پایان اعتبارش معتبر است.",
    };
  }

  return { kind: "OTHER", userMessage: msg };
}

/** آیا خطای ارسال پیامک از نوع «قبلاً ارسال شده» است؟ (راحتی مصرف‌کننده) */
export function isSmsAlreadySent(rawMessage: string): boolean {
  return classifySmsSendFailure(rawMessage).kind === "ALREADY_SENT";
}
