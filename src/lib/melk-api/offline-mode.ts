/**
 * حالت آفلاین SAMنامه‌های ملک تبریز — PN-029 (شورای عالی ملکا · جلسهٔ فوق‌العاده ۰۳۳)
 * ---------------------------------------------------------------------------
 * دکترین مصوب شورا: «در مسائل اتصال به سامانه‌های خارجی، ابتدا تشخیص، سپس
 * اقدام. هیچ تلاش خودکاری بدون تشخیص.»
 *
 * پرچم MELK_ARM_OFFLINE=1 (یا true) یعنی:
 *   ۱) Worker هیچ کاری که به ARM/PM/GAP/سامانهٔ عمومی ملک تبریز متصل شود
 *      اجرا نمی‌کند (catalog-cycle ثبت نمی‌شود — صفر فراخوانی خودکار).
 *   ۲) حلقهٔ همگام‌سازی پس‌زمینه خاموش است (حتی اگر MELK_BACKGROUND_SYNC
 *      فعال شده باشد).
 *   ۳) نشانگرهای اتصال (/api/indicators) پروب زنده نمی‌زنند — آخرین وضعیت
 *      کش‌شده با برچسب «حالت آفلاین» سرو می‌شود (ریشهٔ خطای ۵۰۲ بار اول).
 *   ۴) armCall/probeGet پیش از هر فراخوانی گارد می‌خورند — تنها استثنا:
 *      فراخوانی صریح مالک (API تک‌بارهٔ OTP — سوزاندن آگاهانهٔ یک تلاش).
 *
 * این حالت «توقف تا تشخیص» است، نه حذف اتصال: M1-M5 از دیتابیس محلی کار
 * می‌کنند (صفر قطع خدمت) و پس از رفع ریشه، با برداشتن پرچم همه‌چیز از همان
 * نقطه (checkpoint) ادامه می‌یابد.
 */

/** آیا سامانه در حالت آفلاین ملک تبریز است؟ (فقط خواندن env — خالص و تست‌پذیر) */
export function isArmOfflineMode(): boolean {
  const v = process.env.MELK_ARM_OFFLINE;
  return v === "1" || v === "true" || v === "TRUE" || v === "yes";
}

/** پیام فارسی یکسان برای همهٔ گاردهای حالت آفلاین */
export function offlineModeMessage(): string {
  return "حالت آفلینی ملک تبریز فعال است (PN-029 — توقف تلاش‌های خودکار تا پایان تشخیص). "
    + "M1-M5 از دادهٔ محلی کار می‌کنند؛ برای تلاش دستی، پس از رفع ریشه پرچم MELK_ARM_OFFLINE برداشته می‌شود.";
}

/**
 * آیا این فراخوانی مجاز به عبور از گارد آفلاین است؟
 * فقط فراخوانی صریح و آگاهانهٔ مالک (سوزاندن تک‌تلاش OTP) عبور می‌کند —
 * هیچ مسیر خودکاری bypass نمی‌گیرد (قانون صفر تلاش خودکار).
 */
export function offlineBypassAllowed(bypass?: boolean): boolean {
  return bypass === true;
}
