#!/usr/bin/env bash
# ============================================================================
# drop-cache.sh — PN-078 (سبک‌سازی · آزادسازی رم)
# ----------------------------------------------------------------------------
# کاربرد: scripts/pn078/drop-cache.sh <file> [<file>...]
# کار:    fsync + POSIX_FADV_DONTNEED روی هر فایل — رها کردن page-cache
#         فایل‌های بکاپ سرد (مقدس/چرخشی/قلعه) پس از ساخته‌شدن.
# چرا:    هر چرخهٔ بکاپ ۵۳۶MB در page-cache می‌نشیند؛ بدون این، «رم آزاد»
#         ظاهری ۳۴۷MB از ۴GB می‌ماند در حالی‌که فایل سرد است و هرگز خوانده
#         نمی‌شود (خوانندهٔ بعدی = رستاخیز — از دیسک می‌خواند).
# قرارداد: بهترین-تلاش مطلق — همیشه exit 0؛ شکست هرگز کار فراخوان
#         (بکاپ مقدس) را نمی‌شکند. python3 = همان ابزار واچ‌داگ (بدون FFI).
# ============================================================================
set -uo pipefail

for f in "$@"; do
  [ -f "$f" ] || continue
  python3 - "$f" <<'PYEOF' 2>/dev/null || true
import os, sys
p = sys.argv[1]
try:
    fd = os.open(p, os.O_RDONLY)
    try:
        os.fsync(fd)                                  # صفحات تمیز شوند
        os.posix_fadvise(fd, 0, 0, os.POSIX_FADV_DONTNEED)  # len=0 → کل فایل
    finally:
        os.close(fd)
except Exception:
    pass  # بهترین-تلاش — رم آزاد نشدن به معنای شکست بکاپ نیست
PYEOF
done

exit 0
