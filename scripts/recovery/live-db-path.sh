#!/usr/bin/env bash
# ============================================================
# live-db-path.sh — حل‌کنندهٔ مسیر دیتابیس زندهٔ رسمی (PN-041-R · شورا-ن۰۶۸)
# ------------------------------------------------------------
# معماری تازه: دیتابیس زنده روی «دیسک محلی» db/custom.db (WAL · سریع ·
# پایدار) + سنک ۵دقیقه‌ای به upload/.data (بکاپ چرخشی · منطقهٔ پایدار).
# fallback فقط وقتی محلی غایب/نامعتبر است → قلعهٔ ossfs (تا گارد بوت احیا کند).
# همهٔ گاردهای بازیابی از این حل‌کننده استفاده می‌کنند تا «زنده»
# همیشه همان فایلی باشد که سرور واقعاً سرو می‌کند.
# کاربرد: LIVE="$(bash scripts/recovery/live-db-path.sh)"
# ============================================================
REPO="${REPO_DIR:-/home/z/my-project}"
LOCAL="$REPO/db/custom.db"
FORT="$REPO/upload/.data/custom.db"

if [ -s "$LOCAL" ] && [ "$(head -c 15 "$LOCAL" 2>/dev/null)" = "SQLite format 3" ]; then
  echo "$LOCAL"
elif [ -s "$FORT" ] && [ "$(head -c 15 "$FORT" 2>/dev/null)" = "SQLite format 3" ]; then
  echo "$FORT"    # سرو موقت — گارد قلعه در بوت، محلی را احیا می‌کند
elif [ -s "$LOCAL" ]; then
  echo "$LOCAL"   # موجود اما سرآیند نامعتبر — داوری گارد مقدس
elif [ -s "$FORT" ]; then
  echo "$FORT"    # موجود اما سرآیند نامعتبر — داوری سلامت با گارد قلعه
else
  echo "$LOCAL"   # هیچ — دیسک محلی مقصدِ بازیابی رسمی است (شورا-ن۰۶۸)
fi
